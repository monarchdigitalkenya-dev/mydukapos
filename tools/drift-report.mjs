// Reports how much code is still copy-pasted between the apps and where copies
// have drifted apart. Writes DRIFT_REPORT.md at the project root.
//
//   npm run drift
//
// "Shared" functions (in each app's @shared region) can't drift — they are
// generated from src/shared/functions.js. Everything else that exists in 2+
// apps is listed here, biggest-and-most-diverged first: those are the next
// candidates to reconcile and move into src/shared/.
import crypto from 'node:crypto';
import { MODULES, ROOT, read, write, topLevelFunctions, REGION_RE } from './lib.mjs';

const norm = (t) => t.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').trim();
const hash = (t) => crypto.createHash('md5').update(norm(t)).digest('hex').slice(0, 6);
const short = (m) => (m === 'index.html' ? 'shop(root)' : m.replace('/index.html', ''));

const per = {};
const sharedNames = new Set();
for (const m of MODULES) {
  const html = read(m);
  const region = html.match(REGION_RE);
  const shared = new Set(region ? region[1].split(',') : []);
  shared.forEach((n) => sharedNames.add(n));
  const { decls } = topLevelFunctions(html);
  per[m] = { decls, shared, lines: html.split('\n').length };
}

const names = new Set();
MODULES.forEach((m) => Object.keys(per[m].decls).forEach((n) => names.add(n)));

let totalFnBytes = 0, sharedBytes = 0, dupUnsharedBytes = 0;
const rows = [];
for (const n of [...names].sort()) {
  const have = MODULES.filter((m) => per[m].decls[n]);
  const size = per[have[0]].decls[n][0].src.length;
  have.forEach((m) => { totalFnBytes += per[m].decls[n][0].src.length; });
  if (have.every((m) => per[m].shared.has(n))) { sharedBytes += size * have.length; continue; }
  if (have.length < 2) continue;
  const groups = {};
  have.forEach((m) => { (groups[hash(per[m].decls[n][0].src)] ||= []).push(short(m)); });
  const variants = Object.keys(groups).length;
  const avg = Math.round(have.reduce((a, m) => a + per[m].decls[n][0].src.length, 0) / have.length);
  dupUnsharedBytes += avg * have.length;
  rows.push({ n, apps: have.length, variants, avg, groups: Object.values(groups) });
}

const diverged = rows.filter((r) => r.variants > 1).sort((a, b) => b.avg * b.apps - a.avg * a.apps);
const sameOnlyFormatting = rows.filter((r) => r.variants === 1);

const kb = (b) => (b / 1024).toFixed(0) + ' KB';
let md = `# Drift report\n\n_Generated by \`npm run drift\` — do not edit by hand._\n\n`;
md += `| | |\n|---|---|\n`;
md += `| Functions single-sourced in \`src/shared/\` | ${sharedNames.size} |\n`;
md += `| Source that no longer needs copy-pasting | ${kb(sharedBytes)} |\n`;
md += `| Still duplicated across 2+ apps (unshared) | ${rows.length} functions, ~${kb(dupUnsharedBytes)} |\n`;
md += `| …of which have DIVERGED between apps | ${diverged.length} |\n`;
md += `| …of which are identical apart from comments/whitespace | ${sameOnlyFormatting.length} (safe to promote once exact) |\n\n`;
md += `## Most diverged (biggest first)\n\nEach line lists the apps that share one variant; e.g. \`[shop, hotel] [production]\` = two variants.\n\n`;
md += `| Function | Apps | Variants | ~Size | Groups |\n|---|---|---|---|---|\n`;
for (const r of diverged.slice(0, 60)) {
  md += `| \`${r.n}\` | ${r.apps} | ${r.variants} | ${kb(r.avg)} | ${r.groups.map((g) => '[' + g.join(', ') + ']').join(' ')} |\n`;
}
md += `\n## How to reconcile one\n\n1. Diff the variants (the groups above tell you which apps to compare).\n2. Decide the intended behaviour; where apps genuinely differ, express the difference as a small per-app setting rather than a forked function.\n3. Put the single version in \`src/shared/functions.js\` (\`//@fn name\`), add \`name\` to each app's \`@shared:begin names=…\` list, delete that app's local copy.\n4. \`npm run sync && npm run check\`, then test in the affected apps.\n`;
write('DRIFT_REPORT.md', md);
console.log(md.split('\n').slice(0, 14).join('\n'));
console.log(`\nWrote ${ROOT}/DRIFT_REPORT.md`);
