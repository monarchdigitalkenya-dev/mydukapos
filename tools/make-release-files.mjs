// zip 356: writes tools/release-files.json - the list of every file in this release. tools/deploy-pages.mjs uploads only these
// (plus your local wrangler*.toml), so files a release REMOVED (that robocopy leaves behind in C:\dev\mydukapos) never go live again.
//   node tools/make-release-files.mjs        (run when the zip is packaged, never needed on your PC)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib.mjs';
const SKIP = new Set(['node_modules', '.git', '.wrangler', 'dist', 'build-output', 'backup']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full);
    else files.push(path.relative(ROOT, full).replace(/\\/g, '/'));
  }
})(ROOT);
const out = path.join(ROOT, 'tools', 'release-files.json');
if (!files.includes('tools/release-files.json')) files.push('tools/release-files.json');
files.sort();
fs.writeFileSync(out, JSON.stringify({ note: 'Every file in this release. tools/deploy-pages.mjs uploads only these. Generated by tools/make-release-files.mjs.', files }, null, 0) + '\n');
console.log('release-files.json: ' + files.length + ' files');
