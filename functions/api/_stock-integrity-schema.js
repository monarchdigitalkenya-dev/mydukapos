// functions/api/_stock-integrity-schema.js - shared helper, NOT a route (zip 336). Tables for:
//   store_lots           the batches (lot number, expiry, cost) of stock held in the Store, so a batch-tracked medicine keeps its batch, expiry and
//                        cost when it moves Inventory -> Store -> Inventory. qty CHECK >= 0: two withdrawals at once can never take the same units.
//   cost_corrections     a manager's correction of a wrong cost price (item or one batch): who, when, why, old -> new, the effect. Append-only.
//   profit_adjustments   a manager's documented adjustment of a reported profit (e.g. to zero) for a period. Append-only; undone only by a reversal.
//   cc_settings          small settings (the date the books are closed through).
//   stock_audit          append-only log of manager stock actions (a batch quarantined / recalled / released, packaging changed, opening batch).
// Created on first use by ensureIntegritySchema (also in migrations/0019_stock_integrity.sql, generated by tools/gen-migration.mjs).
export const INTEGRITY_SCHEMA = [
  `CREATE TABLE IF NOT EXISTS store_lots (
  group_id TEXT NOT NULL,
  item_id TEXT NOT NULL,
  lot_id TEXT NOT NULL,
  batch TEXT,
  expiry TEXT,
  cost REAL,
  received_at INTEGER,
  supplier TEXT,
  qty REAL NOT NULL DEFAULT 0 CHECK (qty >= 0),
  updated_at INTEGER NOT NULL,
  PRIMARY KEY (group_id, item_id, lot_id)
) WITHOUT ROWID`,
  `CREATE TABLE IF NOT EXISTS cost_corrections (
  client_id TEXT NOT NULL,
  corr_id TEXT NOT NULL,
  code TEXT NOT NULL,
  name TEXT,
  lot_id TEXT,
  mode TEXT NOT NULL CHECK (mode IN ('forward','restate')),
  old_cost REAL,
  new_cost REAL NOT NULL CHECK (new_cost >= 0),
  date_from TEXT,
  date_to TEXT,
  qty_on_hand REAL,
  value_effect REAL,
  cogs_effect REAL,
  lines_affected INTEGER,
  reason TEXT NOT NULL,
  actor TEXT,
  actor_kind TEXT,
  at INTEGER NOT NULL,
  detail TEXT,
  PRIMARY KEY (client_id, corr_id)
) WITHOUT ROWID`,
  `CREATE INDEX IF NOT EXISTS ix_cost_corrections_code ON cost_corrections (client_id, code, at)`,
  `CREATE TABLE IF NOT EXISTS profit_adjustments (
  client_id TEXT NOT NULL,
  adj_id TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('zero','amount','reversal')),
  date_from TEXT NOT NULL,
  date_to TEXT NOT NULL,
  amount REAL NOT NULL,
  reported_before REAL,
  reported_after REAL,
  reason TEXT NOT NULL,
  reverses TEXT,
  actor TEXT,
  actor_kind TEXT,
  at INTEGER NOT NULL,
  PRIMARY KEY (client_id, adj_id)
) WITHOUT ROWID`,
  `CREATE INDEX IF NOT EXISTS ix_profit_adjustments_period ON profit_adjustments (client_id, date_from, date_to)`,
  `CREATE UNIQUE INDEX IF NOT EXISTS ux_profit_adjustments_reverses ON profit_adjustments (client_id, reverses) WHERE reverses IS NOT NULL`,
  `CREATE TABLE IF NOT EXISTS cc_settings (
  client_id TEXT NOT NULL,
  k TEXT NOT NULL,
  v TEXT NOT NULL,
  actor TEXT,
  updated_at INTEGER NOT NULL,
  PRIMARY KEY (client_id, k)
) WITHOUT ROWID`,
  `CREATE TABLE IF NOT EXISTS stock_audit (
  client_id TEXT NOT NULL,
  ev_id TEXT NOT NULL,
  at INTEGER NOT NULL,
  kind TEXT NOT NULL,
  code TEXT,
  name TEXT,
  detail TEXT,
  reason TEXT,
  actor TEXT,
  actor_kind TEXT,
  PRIMARY KEY (client_id, ev_id)
) WITHOUT ROWID`,
  `CREATE INDEX IF NOT EXISTS ix_stock_audit_at ON stock_audit (client_id, at)`,
  `CREATE TRIGGER IF NOT EXISTS no_delete_stock_audit BEFORE DELETE ON stock_audit BEGIN SELECT RAISE(ABORT, 'the stock audit trail is append-only'); END`,
  `CREATE TRIGGER IF NOT EXISTS no_update_stock_audit BEFORE UPDATE ON stock_audit BEGIN SELECT RAISE(ABORT, 'the stock audit trail is append-only'); END`,
  `CREATE TRIGGER IF NOT EXISTS no_delete_cost_corrections BEFORE DELETE ON cost_corrections BEGIN SELECT RAISE(ABORT, 'cost corrections are never deleted'); END`,
  `CREATE TRIGGER IF NOT EXISTS no_update_cost_corrections BEFORE UPDATE ON cost_corrections BEGIN SELECT RAISE(ABORT, 'cost corrections are never changed: record a new one'); END`,
  `CREATE TRIGGER IF NOT EXISTS no_delete_profit_adjustments BEFORE DELETE ON profit_adjustments BEGIN SELECT RAISE(ABORT, 'profit adjustments are never deleted'); END`,
  `CREATE TRIGGER IF NOT EXISTS no_update_profit_adjustments BEFORE UPDATE ON profit_adjustments BEGIN SELECT RAISE(ABORT, 'profit adjustments are never changed: record a reversal'); END`,
  `CREATE TRIGGER IF NOT EXISTS no_delete_store_lots BEFORE DELETE ON store_lots BEGIN SELECT RAISE(ABORT, 'store batches are never deleted'); END`,
];

const ready = new WeakMap();
export async function ensureIntegritySchema(db) {
  if (ready.get(db)) return db;
  for (const sql of INTEGRITY_SCHEMA) await db.prepare(sql).run();
  ready.set(db, true);
  return db;
}
